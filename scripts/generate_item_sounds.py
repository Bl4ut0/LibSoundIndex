"""Build LibSoundIndex's item sound lookup from versioned DB2 CSV exports."""

import argparse
import csv
from collections import defaultdict
from functools import cache
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUILDS = {
    "Vanilla": ("1.15.9.70576", {11508: "1.15.8.67156"}),
    "TBC": ("2.5.6.70577", {20505: "2.5.5.68575"}),
    "Forever": ("1.60.1.71037", {}),
}


def read_table(folder, table):
    with (folder / f"{table}.csv").open(encoding="utf-8-sig", newline="") as source:
        return list(csv.DictReader(source))


def load_kit_files(folder):
    files = defaultdict(set)
    for row in read_table(folder, "SoundKitEntry"):
        file_id = int(row["FileDataID"])
        if file_id > 0:
            files[int(row["SoundKitID"])].add(file_id)
    return files


def resolve_items(folder, kit_files):
    kit_children = defaultdict(set)
    for row in read_table(folder, "SoundKitChild"):
        kit_children[int(row["ParentSoundKitID"])].add(int(row["SoundKitID"]))

    @cache
    def files_for_kit(kit):
        files, visited = set(), set()
        pending = [kit] if kit > 0 else []
        while pending:
            current = pending.pop()
            if current not in visited:
                visited.add(current)
                files.update(kit_files.get(current, ()))
                pending.extend(kit_children[current] - visited)
        return files

    group_files = {
        int(row["ID"]): set().union(*(
            files_for_kit(int(row[f"Sound_{index}"])) for index in range(4)
        ))
        for row in read_table(folder, "ItemGroupSounds")
    }
    materials = {int(row["ID"]): row for row in read_table(folder, "Material")}
    items = {}
    accessory_files = set()
    for row in read_table(folder, "Item"):
        inventory_type = int(row["InventoryType"])
        if inventory_type <= 0:
            continue
        files = set(group_files.get(int(row["ItemGroupSoundsID"]), ()))
        if inventory_type in (2, 11, 12):  # Neck, finger, trinket
            accessory_files.update(files)
        material = materials.get(int(row["Material"]))
        if material:
            item_class = int(row["ClassID"])
            if item_class == 4:  # Armor
                files.update(files_for_kit(int(material["FoleySoundID"])))
            if item_class == 2 or inventory_type in (14, 23):  # Weapon, shield, holdable
                files.update(files_for_kit(int(material["SheatheSoundID"])))
                files.update(files_for_kit(int(material["UnsheatheSoundID"])))
        if files:
            items[int(row["ID"])] = tuple(sorted(files))
    return items, tuple(sorted(accessory_files))


def lua_array(values):
    return "{" + ",".join(map(str, values)) + "}"


def write_index(output, client, build, items, accessory_files, legacy):
    sound_sets = set(items.values())
    for _, snapshot, _ in legacy.values():
        sound_sets.update(snapshot.values())
    indices = {files: index for index, files in enumerate(sorted(sound_sets), start=1)}
    lines = [
        "-- Generated by scripts/generate_item_sounds.py from build " + build,
        'local lib = LibStub:GetLibrary("LibSoundIndex-1.0", true)',
        f'if not lib or not lib.GetClientKey or lib:GetClientKey() ~= "{client}" then return end',
        "",
        "local fileSets = {",
    ]
    lines.extend("    " + lua_array(files) + "," for files in indices)
    lines += ["}", "", "local itemSets = {"]
    entries = [f"[{item}]={indices[files]}," for item, files in sorted(items.items())]
    for start in range(0, len(entries), 10):
        lines.append("    " + " ".join(entries[start:start + 10]))
    lines += ["}", "", f'local build = "{build}"',
              "local accessoryFiles = " + lua_array(accessory_files)]
    for interface, (snapshot_build, snapshot, snapshot_accessories) in legacy.items():
        lines.append(f"if lib.interfaceVersion == {interface} then")
        lines.append(f'    build = "{snapshot_build}"')
        if accessory_files != snapshot_accessories:
            lines.append("    accessoryFiles = " + lua_array(snapshot_accessories))
        for item in sorted(items.keys() | snapshot.keys()):
            if items.get(item) != snapshot.get(item):
                lines.append(f"    itemSets[{item}] = {indices.get(snapshot.get(item), 'nil')}")
        lines.append("end")
    lines += ["", "lib.ItemSoundData = {",
              "    build = build, fileSets = fileSets, itemSets = itemSets, accessoryFiles = accessoryFiles",
              "}"]
    output.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{client} {build}: {len(items):,} items, {len(indices)} distinct sound file sets")


def write_forever_kits(output, build, kit_files):
    lines = [
        "-- Generated by scripts/generate_item_sounds.py from SoundKitEntry build " + build,
        'local lib = LibStub:GetLibrary("LibSoundIndex-1.0", true)',
        'if not lib or not lib.GetClientKey or lib:GetClientKey() ~= "Forever" then return end',
        "",
        "lib.SoundKitLookup = {",
    ]
    lines.extend(f"    [{kit}] = {lua_array(sorted(files))}," for kit, files in sorted(kit_files.items()))
    lines.append("}")
    output.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--raw-data", type=Path, default=ROOT / "RawData")
    parser.add_argument("--client", choices=BUILDS, action="append")
    args = parser.parse_args()
    out = ROOT / "LibSoundIndex" / "Data"
    for client in args.client or BUILDS:
        build, older_builds = BUILDS[client]
        folder = args.raw_data / build
        kits = load_kit_files(folder)
        items, accessories = resolve_items(folder, kits)
        legacy = {}
        for interface, older_build in older_builds.items():
            older = args.raw_data / older_build
            legacy[interface] = (older_build, *resolve_items(older, load_kit_files(older)))
        write_index(out / f"ItemSounds_{client}.lua", client, build, items, accessories, legacy)
        if client == "Forever":
            write_forever_kits(out / "SoundKitLookup_Forever_1.lua", build, kits)


if __name__ == "__main__":
    main()
